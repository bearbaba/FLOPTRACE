import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {isValidEd25519Did,normalizedProfiles,addProfile,removeProfile} from '../js/did-utils.mjs';

const twoExisting = [
  'did:key:z6MktYZcwhU44paRoi5AwahUv66jKAMsxXvf2TxaUzLs3yyG',
  'did:key:z6MktbDb2dVYvfm2C8koCMxvREpyCRDD1zFPzGgEdJQ1M2AR'
];
const ALPHABET='123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';
function base58(bytes) {
  let n=0n;for(const b of bytes)n=n*256n+BigInt(b);
  let out='';
  while(n){out=ALPHABET[Number(n%58n)]+out;n/=58n;}
  for(const b of bytes){if(b!==0)break;out='1'+out;}
  return out;
}
test('all community DID profiles start empty; no built-in owner accounts in public web',async()=>{
  const source=await readFile(new URL('../js/unified.js',import.meta.url),'utf8');
  const html=await readFile(new URL('../index.html',import.meta.url),'utf8');
  const api=await readFile(new URL('../api/infer.js',import.meta.url),'utf8');
  for(const did of twoExisting){
    assert.equal(source.includes(did),false);
    assert.equal(html.includes(did),false);
    assert.equal(api.includes(did),false);
  }
  assert.match(html,/id="createAgent"/);
  assert.match(html,/id="importAgent"/);
  assert.match(html,/id="statAgents"/);
  assert.match(source,/normalizedProfiles/);
  assert.match(source,/registerProfile/);
});
test('both previously used public Ed25519 DIDs remain importable',()=>{
  assert.ok(twoExisting.every(isValidEd25519Did));
  let list=[];
  list=addProfile(list,{did:twoExisting[0],name:'Main Agent'});
  list=addProfile(list,{did:twoExisting[1],name:'Review Agent'});
  assert.equal(list.length,2);
  assert.throws(()=>addProfile(list,{did:twoExisting[1],name:'Again'}),/already/);
  list=removeProfile(list,twoExisting[0]);
  assert.deepEqual(list,[{name:'Review Agent',did:twoExisting[1]}]);
});
test('reject malformed identifiers, non Ed25519 codec, and invalid registry payloads',()=>{
  assert.equal(isValidEd25519Did('did:key:zInvalid!'),false);
  assert.equal(isValidEd25519Did('did:key:z'+base58(Uint8Array.from([0xed,0x02,...Array(32).fill(0)]))),false);
  assert.equal(isValidEd25519Did('did:key:z'+base58(Uint8Array.from([0xed,0x01,...Array(31).fill(0)]))),false);
  assert.deepEqual(normalizedProfiles(null),[]);
  assert.deepEqual(normalizedProfiles([{did:twoExisting[0],name:'One'}, {did:twoExisting[0],name:'Duplicate'},{did:'bad',name:'Bad'}]),[{did:twoExisting[0],name:'One'}]);
});
test('generator-compatible Ed25519 did:key can be self-served, without a central allowlist',async()=>{
  const subtle=globalThis.crypto?.subtle;
  assert.ok(subtle,'Node 22 WebCrypto expected');
  const pair=await subtle.generateKey({name:'Ed25519'},true,['sign','verify']);
  const jwk=await subtle.exportKey('jwk',pair.publicKey);
  const pub=Buffer.from(jwk.x,'base64url');
  const did='did:key:z'+base58(Uint8Array.from([0xed,0x01,...pub]));
  assert.equal(isValidEd25519Did(did),true);
  assert.notEqual(did,twoExisting[0]);
  assert.equal(addProfile([],{did,name:'A Community Builder'}).length,1);
});
test('passphrase-based backup is generated by client and never sent to server',async()=>{
  const client=await readFile(new URL('../js/unified.js',import.meta.url),'utf8');
  assert.match(client,/window\.CryptoUtil\.encryptBackup\(seedHex,did,pass\)/);
  assert.match(client,/seed\.fill\(0\)/);
  assert.match(client,/privateKey/);
  assert.doesNotMatch(client,/fetch\([^)]*seed/i);
  assert.match(client,/KEY_PROFILES/);
});
